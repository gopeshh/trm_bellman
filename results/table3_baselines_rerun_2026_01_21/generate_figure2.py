#!/usr/bin/env python3
"""
Generate Figure 2: Learning curves for Table 3 baselines.

This script parses evaluation logs from PPO, A2C, DQN, and UPI-TRM training runs
and generates learning curves showing success rate vs training steps.

It also reads the random baseline from a separate file (generated by
scripts/eval_random_policy.py) to show as a horizontal reference line.

Usage:
    python results/table3_baselines_rerun_2026_01_21/generate_figure2.py

To regenerate the random baseline first:
    python scripts/eval_random_policy.py \\
        --dataset-path data/sudoku-4x4-trivial \\
        --output results/plot_data/random_baseline.csv
"""

import re
import json
import csv
from pathlib import Path
from typing import Optional, Tuple, List, Dict

import matplotlib.pyplot as plt
import numpy as np

# Directory containing logs
LOG_DIR = Path(__file__).parent
PLOT_DATA_DIR = LOG_DIR.parent / "plot_data"

# Methods and seeds
METHODS = ["ppo", "a2c", "dqn", "upitrm"]
SEEDS = [42, 123, 456]

# Colors for methods (colorblind-friendly)
COLORS = {
    "ppo": "#E69F00",      # Orange
    "a2c": "#56B4E9",      # Sky blue
    "dqn": "#CC79A7",      # Reddish purple
    "upitrm": "#009E73",   # Bluish green
    "random": "#999999",   # Gray
}

LABELS = {
    "ppo": "PPO",
    "a2c": "A2C",
    "dqn": "DQN",
    "upitrm": "UPI-TRM (Ours)",
    "random": "Random (action mask)",
}


def parse_log(log_path: Path) -> Tuple[List[int], List[float]]:
    """Parse eval_success_rate from log file.

    Handles two formats:
    1. step 00100/05000 ... eval_success_rate=0.20
    2. [step 00100] eval_success_rate=0.200 ...

    Returns:
        steps: List of training steps
        success_rates: List of success rates (0-100)
    """
    steps = []
    success_rates = []

    # Pattern 1: step 00100/05000 ... eval_success_rate=0.20
    pattern1 = re.compile(r"step\s+(\d+)/\d+.*eval_success_rate=([0-9.]+)")
    # Pattern 2: [step 00100] eval_success_rate=0.200
    pattern2 = re.compile(r"\[step\s+(\d+)\].*eval_success_rate=([0-9.]+)")

    with open(log_path, "r") as f:
        for line in f:
            match = pattern1.search(line) or pattern2.search(line)
            if match:
                step = int(match.group(1))
                rate = float(match.group(2)) * 100  # Convert to percentage
                steps.append(step)
                success_rates.append(rate)

    return steps, success_rates


def load_random_baseline(
    csv_path: Optional[Path] = None,
    json_path: Optional[Path] = None,
) -> Tuple[Optional[float], Optional[float]]:
    """
    Load random baseline success rate from file.
    
    Tries JSON first (more complete), then CSV.
    
    Returns:
        (mean_success_rate, std_success_rate) as percentages, or (None, None) if not found
    """
    # Default paths
    if csv_path is None:
        csv_path = PLOT_DATA_DIR / "random_baseline.csv"
    if json_path is None:
        json_path = PLOT_DATA_DIR / "random_baseline.json"
    
    # Try JSON first
    if json_path.exists():
        try:
            with open(json_path, "r") as f:
                data = json.load(f)
            agg = data.get("aggregate", {})
            mean = agg.get("success_rate_mean")
            std = agg.get("success_rate_std")
            if mean is not None:
                return mean * 100, (std * 100 if std else 0.0)
        except Exception as e:
            print(f"Warning: Failed to parse {json_path}: {e}")
    
    # Try CSV
    if csv_path.exists():
        try:
            with open(csv_path, "r") as f:
                reader = csv.DictReader(f)
                rows = list(reader)
            # Find the "mean" row
            for row in rows:
                if row.get("seed") == "mean":
                    rate = float(row["success_rate"])
                    return rate * 100, 0.0
            # If no mean row, compute from individual seeds
            rates = [float(r["success_rate"]) for r in rows if r.get("seed") != "mean"]
            if rates:
                mean = sum(rates) / len(rates)
                std = (sum((r - mean)**2 for r in rates) / len(rates)) ** 0.5
                return mean * 100, std * 100
        except Exception as e:
            print(f"Warning: Failed to parse {csv_path}: {e}")
    
    return None, None


def main():
    # Collect data
    data: Dict[str, Dict] = {}

    for method in METHODS:
        data[method] = {"steps": None, "rates": [], "available": True}

        for seed in SEEDS:
            log_name = f"{method}_s{seed}.log"
            log_path = LOG_DIR / log_name

            # Also try _fixed suffix for re-run logs
            if not log_path.exists():
                log_path = LOG_DIR / f"{method}_s{seed}_fixed.log"

            if not log_path.exists():
                print(f"Warning: {log_name} not found")
                continue

            steps, rates = parse_log(log_path)

            if not steps:
                print(f"Warning: No eval data in {log_name}")
                data[method]["available"] = False
                continue

            print(f"{log_path.name}: {len(steps)} eval points, final={rates[-1]:.1f}%")

            if data[method]["steps"] is None:
                data[method]["steps"] = steps
            data[method]["rates"].append(rates)

    # Load random baseline
    random_mean, random_std = load_random_baseline()
    if random_mean is not None:
        print(f"Random baseline: {random_mean:.1f}% ± {random_std:.1f}%")
    else:
        print("Warning: Random baseline not found (run scripts/eval_random_policy.py first)")

    # Create figure
    fig, ax = plt.subplots(figsize=(8, 5))

    # Track which methods have data for legend ordering
    plotted_methods = []

    for method in METHODS:
        if not data[method]["rates"]:
            if not data[method]["available"]:
                # Method exists but eval failed (e.g., DQN bug)
                pass
            continue

        steps = np.array(data[method]["steps"])
        rates = np.array(data[method]["rates"])

        # Handle case where seeds have different lengths
        min_len = min(len(r) for r in rates)
        steps = steps[:min_len]
        rates = np.array([r[:min_len] for r in rates])

        # Compute mean and std
        mean_rate = rates.mean(axis=0)
        std_rate = rates.std(axis=0)

        # Plot mean line
        ax.plot(steps, mean_rate,
                color=COLORS[method],
                linewidth=2,
                label=LABELS[method])

        # Plot shaded std region
        ax.fill_between(steps,
                        mean_rate - std_rate,
                        mean_rate + std_rate,
                        color=COLORS[method],
                        alpha=0.2)

        plotted_methods.append(method)

    # Add random baseline as horizontal line
    if random_mean is not None:
        ax.axhline(y=random_mean, color=COLORS["random"], linestyle="--",
                   linewidth=1.5, label=LABELS["random"])
        if random_std and random_std > 0:
            ax.axhspan(random_mean - random_std, random_mean + random_std,
                       color=COLORS["random"], alpha=0.1)

    # Formatting
    ax.set_xlabel("Training Steps", fontsize=12)
    ax.set_ylabel("Success Rate (%)", fontsize=12)
    ax.set_title("Learning Curves on 4×4 Sudoku (ULTRA-EASY)", fontsize=14)
    ax.set_xlim(0, 5000)
    ax.set_ylim(0, 105)
    ax.set_yticks([0, 20, 40, 60, 80, 100])
    ax.grid(True, alpha=0.3)
    ax.legend(loc="lower right", fontsize=11)

    # Add note if DQN eval was unavailable
    if "dqn" in data and not data["dqn"]["rates"]:
        ax.text(0.02, 0.98, "DQN: eval unavailable (bug)",
                transform=ax.transAxes, fontsize=9,
                verticalalignment="top", style="italic", color="gray")

    plt.tight_layout()

    # Save
    output_path = LOG_DIR / "figure2_learning_curves.pdf"
    plt.savefig(output_path, dpi=300, bbox_inches="tight")
    print(f"\nSaved: {output_path}")

    # Also save PNG for quick preview
    png_path = LOG_DIR / "figure2_learning_curves.png"
    plt.savefig(png_path, dpi=150, bbox_inches="tight")
    print(f"Saved: {png_path}")

    # Also copy to paper figures directory if it exists
    paper_fig_dir = Path("/Users/buiksat/UPI_TRM/UPI_TRM_ICML/figures")
    if paper_fig_dir.exists():
        paper_output = paper_fig_dir / "trivial_baselines_vs_no_contraction_success_vs_steps.pdf"
        import shutil
        shutil.copy(output_path, paper_output)
        print(f"Copied to: {paper_output}")


if __name__ == "__main__":
    main()
